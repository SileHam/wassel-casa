import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
import { restaurants, quote } from "../lib/catalog.ts";

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.WASSEL_PLAYWRIGHT_MODULE || "playwright");
const base = process.env.WASSEL_BASE_URL || "http://127.0.0.1:5173";
const browser = await chromium.launch({ channel: "msedge", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
const page = await context.newPage();
const failures = [];
page.on("pageerror", error => failures.push(error.message));
mkdirSync(".sites-runtime/qa", { recursive: true });
try {
  assert.equal(quote(restaurants[0], [{ id: "tajine", quantity: 1 }], "CASA10").discount, 0);
  assert.equal(quote(restaurants[0], [{ id: "tajine", quantity: 2 }, { id: "salade", quantity: 1 }], "CASA10").total, 12900);
  assert.throws(() => quote(restaurants[0], [{ id: "tajine", quantity: -1 }]));
  assert.equal((await context.request.get(`${base}/api/orders`)).status(), 401);
  await page.goto(`${base}/signin-with-chatgpt?return_to=/`);
  await page.getByRole("heading", { name: "Casa a faim. On s’en occupe." }).waitFor();
  await page.locator('.app-shell[data-ready="true"]').waitFor();
  await page.screenshot({ path: ".sites-runtime/qa/desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Voir le menu de Beldi & Bon" }).click();
  await page.getByRole("button", { name: "Ajouter Tajine poulet citron", exact: true }).click();
  await page.getByRole("button", { name: "Ajouter Tajine poulet citron", exact: true }).click();
  await page.getByRole("button", { name: "Ajouter Salade marocaine", exact: true }).click();
  await page.getByRole("button", { name: /Voir mon panier/ }).click();
  await page.getByLabel("Adresse de test", { exact: true }).fill("24 rue de démonstration");
  await page.getByLabel("Code promotionnel").fill("CASA10");
  await page.getByRole("button", { name: "Appliquer", exact: true }).click();
  const createdResponse = page.waitForResponse(response => response.url() === `${base}/api/orders` && response.request().method() === "POST");
  await page.getByRole("button", { name: /Créer la commande de test/ }).click();
  const created = await createdResponse;
  assert.equal(created.status(), 201, await created.text());
  const { id } = await created.json();
  await page.getByRole("heading", { name: "Votre envie prend forme." }).waitFor();
  const getOrders = async () => (await (await context.request.get(`${base}/api/orders`)).json()).orders;
  assert.equal((await getOrders()).find(order => order.id === id).total, 12900);
  await page.getByRole("button", { name: "Restaurant", exact: true }).click();
  await page.getByRole("heading", { name: "Côté cuisine." }).waitFor();
  let row = page.locator(".order-card").filter({ hasText: id.slice(0, 8).toUpperCase() });
  await row.getByRole("button", { name: "Accepter la commande" }).click();
  await row.getByRole("button", { name: "Prête à récupérer" }).click();
  await page.locator(".role-tabs").getByRole("button", { name: "Livreur", exact: true }).click();
  row = page.locator(".order-card").filter({ hasText: id.slice(0, 8).toUpperCase() });
  await row.getByRole("button", { name: "Confirmer la récupération" }).click();
  await row.getByRole("button", { name: "Confirmer la livraison" }).click();
  await page.waitForTimeout(500);
  assert.equal((await getOrders()).find(order => order.id === id).status, "delivered");
  await page.reload();
  assert.equal((await getOrders()).find(order => order.id === id).status, "delivered");

  const input = { requestKey: crypto.randomUUID(), restaurantId: "beldi", lines: [{ id: "tajine", quantity: 1 }], district: "Maârif", address: "24 rue fictive", note: "", slot: "soon", promo: "", total: 1 };
  const post = body => context.request.post(`${base}/api/orders`, { headers: { Origin: base }, data: body });
  const duplicate = await Promise.all([post(input), post(input)]);
  const duplicateIds = await Promise.all(duplicate.map(async response => { assert.ok([200,201].includes(response.status()), await response.text()); return (await response.json()).id; }));
  assert.equal(duplicateIds[0], duplicateIds[1]);
  assert.equal((await getOrders()).find(order => order.id === duplicateIds[0]).total, 7300, "server ignores client totals");
  const patch = body => context.request.patch(`${base}/api/orders/${duplicateIds[0]}`, { headers: { Origin: base }, data: body });
  assert.equal((await patch({ action: "status", from: "pending", to: "delivered" })).status(), 400);
  const race = await Promise.all([patch({ action: "status", from: "pending", to: "cancelled" }), patch({ action: "status", from: "pending", to: "preparing" })]);
  assert.deepEqual(race.map(response => response.status()).sort(), [200, 409]);
  assert.equal((await patch({ action: "support", message: "Test de signalement enregistré" })).status(), 200);
  assert.equal((await getOrders()).find(order => order.id === duplicateIds[0]).issue, "Test de signalement enregistré");
  assert.equal((await post({ ...input, requestKey: crypto.randomUUID(), lines: [{ id: "tajine", quantity: -2 }] })).status(), 400);
  assert.equal((await context.request.post(`${base}/api/orders`, { headers: { Origin: "https://example.invalid" }, data: input })).status(), 403);
  const anonymous = await browser.newContext();
  assert.equal((await anonymous.request.get(`${base}/api/orders`)).status(), 401);
  assert.equal((await anonymous.request.patch(`${base}/api/orders/${id}`, { headers: { Origin: base }, data: { action: "support", message: "unauthorized" } })).status(), 401);
  await anonymous.close();

  await page.goto(base);
  await page.locator('.app-shell[data-ready="true"]').waitFor();
  await page.getByRole("button", { name: "Ajouter Beldi & Bon des favoris" }).click();
  await page.getByRole("button", { name: "Mes favoris", exact: true }).click();
  assert.equal(await page.locator(".restaurant-card").count(), 1);
  await page.getByRole("button", { name: "Wassel accueil" }).click();
  await page.getByRole("textbox", { name: "Rechercher un restaurant ou un plat" }).fill("not-a-real-dish");
  await page.getByRole("heading", { name: "Pas encore de pépite pour cette recherche." }).waitFor();
  await page.getByRole("button", { name: "Découvrir les adresses", exact: true }).click();
  await page.getByRole("button", { name: "Livraison offerte", exact: true }).click();
  assert.equal(await page.locator(".restaurant-card").count(), 1);
  await page.getByRole("button", { name: "Toutes les adresses", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: ".sites-runtime/qa/mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "mobile has no horizontal overflow");
  await page.getByRole("button", { name: "Voir le menu de Ciao Napoli" }).click();
  await page.getByRole("button", { name: "Ajouter Margherita", exact: true }).click();
  await page.getByRole("button", { name: /Voir mon panier/ }).click();
  await page.getByRole("heading", { name: "Votre petite sélection." }).waitFor();
  await page.screenshot({ path: ".sites-runtime/qa/mobile-checkout.png", fullPage: false });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  assert.deepEqual(failures, [], "no browser runtime exceptions");
  console.log("PASS: pricing, complete browser ordering flow, persistence, role queues, idempotency, price integrity, transitions, race handling, support, validation, origin checks, authentication, favorites, search, filters and mobile layout.");
} finally { await browser.close(); }
